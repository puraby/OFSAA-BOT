def _api_post(path: str, payload: Dict[str, Any], timeout: int = 30) -> Optional[Dict[str, Any]]:
    try:
        r = requests.post(f"{API_BASE}{path}", json=payload, timeout=timeout)
        r.raise_for_status()
        return r.json()
    except Exception:
        return None

def call_chat(question: str, schema: str, tone: str) -> Dict[str, Any]:
    """
    Calls /chat for LLM-generated, human-like replies.
    Falls back to deterministic mock aligned to demo content.
    """
    payload = {"message": question, "schema": schema, "tone": tone}
    data = _api_post("/chat", payload)
    if data:
        return data

    # Mock fallback: reply + tables + sql_snippets
    mock_schema = schema or "OFSAAFCCM"
    mock_tables = [
        {"OWNER": mock_schema, "TABLE_NAME": "TXN_ALERTS", "COMMENTS": "Alerts generated by batch (daily)"},
        {"OWNER": mock_schema, "TABLE_NAME": "ALERT_HISTORY", "COMMENTS": "Alert timeline and status transitions"},
        {"OWNER": mock_schema, "TABLE_NAME": "STG_PARTY_MASTER", "COMMENTS": "Staging for party/customer info"},
    ]
    mock_sql = [
        "SELECT owner, table_name, comments\n"
        "FROM all_tab_comments\n"
        "WHERE owner=:owner AND (LOWER(table_name) LIKE LOWER(:kw) OR LOWER(comments) LIKE LOWER(:kw2))\n"
        "ORDER BY table_name"
    ]
    reply = (
        f"(Mock) Tables matching your query in {mock_schema}. I found {len(mock_tables)} rows.\n\n"
        "• TXN_ALERTS — Alerts generated by batch (daily)\n"
        "• ALERT_HISTORY — Alert timeline and status transitions\n"
        "• STG_PARTY_MASTER — Staging for party/customer info\n\n"
        "I can narrow this down or switch to columns/keys/partitions."
    )
    return {"reply": reply, "tables": mock_tables, "sql_snippets": mock_sql}

def call_explain(schema: str, keyword: str) -> Dict[str, Any]:
    """
    Calls /explain for keyword-based table discovery + relationship graph summary.
    Falls back to mock graph consistent with demo tables.
    """
    payload = {"schema": schema, "keyword": keyword}
    data = _api_post("/explain", payload)
    if data:
        # unify shape to match chat renderer (answer/reply + tables + sql)
        return {
            "reply": data.get("summary"),
            "tables": data.get("tables"),
            "sql_snippets": data.get("sql_snippets"),
        }

    mock_schema = schema or "OFSAAFCCM"
    mock_tables = [
        {"OWNER": mock_schema, "TABLE_NAME": "TXN_ALERTS", "COMMENTS": "Alerts generated by batch (daily)"},
        {"OWNER": mock_schema, "TABLE_NAME": "ALERT_HISTORY", "COMMENTS": "Alert timeline and status transitions"},
        {"OWNER": mock_schema, "TABLE_NAME": "STG_PARTY_MASTER", "COMMENTS": "Staging for party/customer info"},
    ]
    mock_sql = [
        "/* find tables */ SELECT owner, table_name, comments FROM all_tab_comments WHERE owner=:owner AND UPPER(table_name) LIKE :kw",
        "/* fk edges */ SELECT ... FROM all_constraints ...",
        "/* pk cols */ SELECT ... FROM all_constraints ...",
    ]
    summary = (
        f"(Mock) I found {len(mock_tables)} rows related to ALERT in {mock_schema}. Here’s how they connect:\n"
        "• ALERT_HISTORY → TXN_ALERTS via (ALERT_ID) → (ALERT_ID)\n"
        "• TXN_ALERTS → STG_PARTY_MASTER via (PARTY_ID) → (PARTY_ID)\n\n"
        "**Table notes:**\n"
        "• TXN_ALERTS — Alerts generated by batch (daily)\n"
        "• ALERT_HISTORY — Alert timeline and status transitions\n"
        "• STG_PARTY_MASTER — Staging for party/customer info"
    )
    return {"reply": summary, "tables": mock_tables, "sql_snippets": mock_sql}

def typing_write(text: str, delay: float = 0.0):
    """
    Simple typing effect; set delay>0 for demo flair.
    """
    if not delay:
        st.markdown(text)
        return
    ph = st.empty()
    buf = ""
    for ch in text:
        buf += ch
        ph.markdown(buf)
        time.sleep(delay)

def message(role: str, content: Any, typing_delay: float = 0.0):
    with st.chat_message("user" if role == "user" else "assistant"):
        if role == "user":
            st.write(content)
        else:
            # Prefer LLM "reply"; fallback to deterministic "answer"
            text = content.get("reply") or content.get("answer") or ""
            typing_write(text, delay=typing_delay)

            # Results Tabs
            tabs = st.tabs(["Results", "SQL Used", "Notes"])
            with tabs[0]:
                if content.get("tables"):
                    with st.container():
                        st.markdown("<div class='card tight-table'>", unsafe_allow_html=True)
                        st.dataframe(content["tables"], use_container_width=True)
                        st.markdown("</div>", unsafe_allow_html=True)
                else:
                    st.info("No rows to display.")
            with tabs[1]:
                if content.get("sql_snippets"):
                    for s in content["sql_snippets"]:
                        st.code(s, language="sql")
                else:
                    st.caption("No SQL captured.")
            with tabs[2]:
                st.caption("Read-only • Dictionary views only • Parametrised queries • Audit friendly")

