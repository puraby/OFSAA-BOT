# -----------------------------
# Session State
# -----------------------------
if "history" not in st.session_state:
    st.session_state.history = []  # <-- fixed init

# -----------------------------
# Handle Quick Prompts
# -----------------------------
if "pending_prompt" in st.session_state:
    job = st.session_state.pop("pending_prompt")
    if job.get("type") == "explain":
        kw = job.get("kw", "ALERT")
        st.session_state.history.append(("user", f"Explain how {kw} tables are connected"))
        with st.spinner("Analyzing relationships..."):
            data = call_explain(schema, kw)
            time.sleep(0.15)
        st.session_state.history.append(("assistant", data))
    else:
        q = job.get("q", "")
        st.session_state.history.append(("user", q))
        with st.spinner("Thinking..."):
            data = call_chat(q, schema, tone)
            time.sleep(0.15)
        st.session_state.history.append(("assistant", data))

